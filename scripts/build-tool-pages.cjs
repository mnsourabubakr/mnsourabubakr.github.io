const { readFileSync, writeFileSync, existsSync } = require('node:fs');
const { resolve } = require('node:path');
const { runInNewContext } = require('node:vm');
const content = require('./product-content.cjs');
const captures = require('./product-media.json');
const { renderProduct } = require('./render-product.cjs');
const { structuredData, escapeHtml: esc } = require('../js/tool-landing.js');

const root = resolve(__dirname, '..');
const read = file => readFileSync(resolve(root, file), 'utf8').replace(/\r\n/g, '\n');
const tools = runInNewContext(read('js/tools-data.js') + '\nTOOLS;');
const legacy = read('tool.html');
const nav = legacy.match(/<!-- NAV -->\n([\s\S]*?)<!-- TOOL CONTENT -->/)[1]
  .replace('<nav class="nav">', '<nav class="nav" aria-label="Main navigation">');
const footer = legacy.match(/<footer class="footer">[\s\S]*?<\/footer>/)[0];
const siteBase = 'https://mnsourabubakr.github.io/';
const routeFiles = { '10': 'room-wizard.html' };
const localDemoIds = new Set(['01', '02', '03', '06', '07', '08', '09', '13']);
const check = process.argv.includes('--check');

function emit(file, html) {
  if (check) {
    if (!existsSync(resolve(root, file)) || read(file) !== html) throw new Error(`${file} is out of date. Run node scripts/build-tool-pages.cjs.`);
  } else {
    writeFileSync(resolve(root, file), html);
  }
}

function validateAsset(asset) {
  if (!(asset.width > 0 && asset.height > 0 && asset.alt && existsSync(resolve(root, asset.src)))) {
    throw new Error(`Invalid product image: ${asset.src}`);
  }
  return asset;
}

function existingImage(file, alt) {
  const bytes = readFileSync(resolve(root, file));
  if (bytes.toString('ascii', 12, 16) !== 'IHDR') throw new Error(`Expected a PNG product screenshot: ${file}`);
  return validateAsset({ src: file, width: bytes.readUInt32BE(16), height: bytes.readUInt32BE(20), alt });
}

function renderPage(tool, file) {
  const pageUrl = new URL(file, siteBase).href;
  const imageUrl = new URL(tool.heroImage.src, siteBase).href;
  const title = `${tool.name} for Revit | BIM Sprint`;
  const description = tool.lead;
  const schema = JSON.stringify(structuredData(tool, pageUrl, imageUrl, siteBase)).replace(/</g, '\\u003c');
  return `<!doctype html>
<!-- Generated by scripts/build-tool-pages.cjs. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<meta name="robots" content="index,follow,max-image-preview:large">
<meta name="theme-color" content="#071b2e">
<link rel="canonical" href="${pageUrl}">
<link rel="icon" type="image/png" href="assets/images/favicon.png">
<link rel="apple-touch-icon" href="assets/images/favicon-192.png">
<link rel="manifest" href="site.webmanifest">
<link rel="stylesheet" href="css/style.css?v=in-page-request">
<link rel="stylesheet" href="css/tool-landing.css?v=8">
<link rel="stylesheet" href="css/product-detail.css?v=${tool.localDemo ? 'local-demo' : '1'}">
<meta property="og:type" content="website">
<meta property="og:site_name" content="BIM Sprint">
<meta property="og:title" content="${esc(title)}">
<meta property="og:description" content="${esc(description)}">
<meta property="og:url" content="${pageUrl}">
<meta property="og:image" content="${imageUrl}">
<meta property="og:image:alt" content="${esc(tool.heroImage.alt)}">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${esc(title)}">
<meta name="twitter:description" content="${esc(description)}">
<meta name="twitter:image" content="${imageUrl}">
<script type="application/ld+json">${schema}</script>
</head>
<body class="product-detail-page">
<a class="rw-skip" href="#tool-content">Skip to content</a>
${nav}<main class="rw-page" id="tool-content" tabindex="-1">${renderProduct(tool)}
</main>
${footer}
<script src="js/main.js" defer></script>
<script src="js/product-events.js${tool.localDemo ? '?v=local-demo' : ''}" defer></script>
<script src="js/package-selection.js?v=product-landing-pages" defer></script>
<script src="js/package-request.js?v=in-page-request" defer></script>
</body>
</html>
`;
}

for (const [id, source] of Object.entries(tools)) {
  if (id === '10') continue;
  if (!content[id]) throw new Error(`Missing product page content for tool ${id}`);
  const tool = { ...source, ...content[id], id };
  const file = `${tool.slug}.html`;
  const pkg = /^Package (0[1-4])\b/.exec(tool.pkg);
  tool.packageId = pkg ? `pkg${pkg[1]}` : 'shared';
  const fallback = existingImage(tool.image, `${tool.name} workspace in Autodesk Revit.`);
  tool.heroImage = captures[id]?.hero ? validateAsset(captures[id].hero) : fallback;
  tool.exampleImage = captures[id]?.example ? validateAsset(captures[id].example) : { ...fallback, alt: tool.visual };
  tool.demoImages = [captures[id]?.demo1, captures[id]?.demo2].map(asset => asset && validateAsset(asset));
  if (localDemoIds.has(id)) {
    const assetBase = `assets/videos/tool-demos/${tool.slug}`;
    tool.localDemo = { src: `${assetBase}.mp4`, poster: `${assetBase}.webp` };
    for (const file of Object.values(tool.localDemo)) {
      if (!existsSync(resolve(root, file))) throw new Error(`Missing demo asset: ${file}`);
    }
  }
  routeFiles[id] = file;
  emit(file, renderPage(tool, file).replace(/[ \t]+$/gm, ''));
}

emit('js/product-routes.js', `// Generated by scripts/build-tool-pages.cjs.
(() => {
  const routes = ${JSON.stringify(routeFiles, null, 2)};
  const params = new URLSearchParams(window.location.search);
  const id = params.get('id');
  if (!Object.hasOwn(routes, id)) return;
  params.delete('id');
  const query = params.toString();
  window.location.replace(routes[id] + (query ? '?' + query : '') + window.location.hash);
})();
`);
