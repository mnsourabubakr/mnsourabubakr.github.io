// Generate the checked-in, JavaScript-independent page for GitHub Pages.
const { readFileSync, writeFileSync } = require('node:fs');
const { resolve } = require('node:path');
const { runInNewContext } = require('node:vm');
const { renderToolLandingPage, structuredData, escapeHtml } = require('../js/tool-landing.js');

const root = resolve(__dirname, '..');
const read = file => readFileSync(resolve(root, file), 'utf8');
const tool = runInNewContext(read('js/tools-data.js') + '\nTOOLS["10"];');
const shared = read('tool.html').replace(/\r\n/g, '\n');
const nav = shared.match(/<!-- NAV -->\n([\s\S]*?)<!-- TOOL CONTENT -->/)[1]
  .replace('<nav class="nav">', '<nav class="nav" aria-label="Main navigation">');
const footer = shared.match(/<footer class="footer">[\s\S]*?<\/footer>/)[0];

const siteBase = 'https://mnsourabubakr.github.io/';
const pageUrl = new URL('room-wizard.html', siteBase).href;
const imageUrl = new URL(tool.image, siteBase).href;
const title = escapeHtml(tool.seo.title);
const description = escapeHtml(tool.seo.description);
const schema = JSON.stringify(structuredData(tool, pageUrl, imageUrl, siteBase)).replace(/</g, '\\u003c');
const html = `<!doctype html>
<!-- Generated by scripts/build-room-wizard.cjs. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${title}</title>
<meta name="description" content="${description}">
<meta name="robots" content="index,follow,max-image-preview:large">
<meta name="theme-color" content="#071b2e">
<link rel="canonical" href="${pageUrl}">
<link rel="icon" type="image/png" href="assets/images/favicon.png">
<link rel="apple-touch-icon" href="assets/images/favicon-192.png">
<link rel="manifest" href="site.webmanifest">
<link rel="stylesheet" href="css/style.css?v=20260925-tool-demos">
<link rel="stylesheet" href="css/tool-landing.css?v=3">
<meta property="og:type" content="website">
<meta property="og:site_name" content="BIM Sprint">
<meta property="og:title" content="${title}">
<meta property="og:description" content="${description}">
<meta property="og:url" content="${pageUrl}">
<meta property="og:image" content="${imageUrl}">
<meta property="og:image:alt" content="Room Wizard floor finishes workspace in Revit">
<meta name="twitter:card" content="summary_large_image">
<meta name="twitter:title" content="${title}">
<meta name="twitter:description" content="${description}">
<meta name="twitter:image" content="${imageUrl}">
<script type="application/ld+json">${schema}</script>
</head>
<body class="room-wizard-page-active">
<a class="rw-skip" href="#tool-content">Skip to content</a>
${nav}<main class="rw-page" id="tool-content" tabindex="-1">${renderToolLandingPage(tool)}
</main>
${footer}
<script src="js/main.js" defer></script>
<script src="js/room-wizard.js" defer></script>
</body>
</html>
`;

const output = resolve(root, 'room-wizard.html');
if (process.argv.includes('--check')) {
  if (read('room-wizard.html').replace(/\r\n/g, '\n') !== html) {
    throw new Error('Room Wizard HTML is out of date. Run node scripts/build-room-wizard.cjs.');
  }
} else {
  writeFileSync(output, html);
}
